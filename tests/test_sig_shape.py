# ---------------------------------------------------------------------------
# Edge case: 87-char string with a reachable tail
# ---------------------------------------------------------------------------


class EightySevenCharEdgeCaseTests(unittest.TestCase):
    """The 87-char / 65-byte-tail edge case documented in the module."""

    def test_87_char_with_aqgw_tail_is_rejected_on_length(self) -> None:
        # A 65-byte tail encodes to 88 base64url characters, but a
        # parser that *truncates* an 88-char string to 87 (e.g. by
        # stripping one trailing '=') can produce a string whose
        # tail character is in {A, Q, g, w}. The length check is
        # what stops this.
        for tail in TAIL_CHARS:
            s = "A" * 86 + tail
            self.assertEqual(len(s), 87)
            self.assertFalse(
                is_canonical_signature_shape(s),
                f"87-char string ending in {tail!r} must be rejected",
            )
            result = validate_signature_shape(s)
            self.assertFalse(result.valid)
            self.assertIn("length is 87", result.reason or "")

    def test_length_check_runs_before_tail_check(self) -> None:
        # If a caller swapped the order so the tail check ran
        # first, an 87-char string ending in 'A' would *pass* the
        # tail check, which is a security regression. The length
        # check must run first.
        s = "A" * 86 + "A"
        result = validate_signature_shape(s)
        self.assertFalse(result.valid)
        self.assertIn("length is 87", result.reason or "")


