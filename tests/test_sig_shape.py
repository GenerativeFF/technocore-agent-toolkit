class DeterminismTests(unittest.TestCase):
    """The function is deterministic over its input."""

    def test_repeated_calls_agree(self) -> None:
        s = _make_valid_86_char_string("g")
        results = [is_canonical_signature_shape(s) for _ in range(100)]
        self.assertTrue(all(results))

    def test_validate_is_deterministic(self) -> None:
        s = "A" * 86
        results = [validate_signature_shape(s) for _ in range(100)]
        self.assertTrue(all(r.valid for r in results))
        self.assertTrue(all(r.reason is None for r in results))


# ---------------------------------------------------------------------------
# Schema check against the documented vectors file (no required vectors
# for this module yet; we just confirm the loader would accept the
# shape of an entry).
# ---------------------------------------------------------------------------


class VectorSchemaTests(unittest.TestCase):
    """If/when vectors/ includes a sig-shape file, the schema is known."""

    def test_vector_file_path_convention(self) -> None:
        # The vectors/ directory is reserved for sanitized public
        # test data. The signature-shape contract is fully
        # deterministic from constants and the Ed25519
        # specification, so it does not yet need a vector file.
        # This test documents the path that *would* be used.
        repo = _REPO
        candidates = [
            os.path.join(repo, "vectors", "sig_shape_cases.json"),
        ]
        # The file does not have to exist; the test only asserts
        # that if it did, the loader would not crash on a
        # well-formed JSON object.
        for path in candidates:
            if os.path.isfile(path):
                with open(path, "r", encoding="utf-8") as fh:
                    data = json.load(fh)
                self.assertIsInstance(data, dict)


