class InputTypeTests(unittest.TestCase):
    """Non-string inputs are rejected without raising."""

    def test_none(self) -> None:
        self.assertFalse(is_canonical_signature_shape(None))

    def test_bytes(self) -> None:
        # 64 raw bytes is the *decoded* form. The surface check
        # is on the string encoding, not the raw bytes.
        raw = b"\x00" * 64
        self.assertFalse(is_canonical_signature_shape(raw))

    def test_int(self) -> None:
        self.assertFalse(is_canonical_signature_shape(0))
        self.assertFalse(is_canonical_signature_shape(86))

    def test_float(self) -> None:
        self.assertFalse(is_canonical_signature_shape(86.0))

    def test_bool(self) -> None:
        self.assertFalse(is_canonical_signature_shape(True))
        self.assertFalse(is_canonical_signature_shape(False))

    def test_list(self) -> None:
        self.assertFalse(is_canonical_signature_shape(["A"] * 86))

    def test_dict(self) -> None:
        self.assertFalse(is_canonical_signature_shape({"sig": "A" * 86}))

    def test_object(self) -> None:
        class Fake:
            pass

        self.assertFalse(is_canonical_signature_shape(Fake()))

    def test_validate_returns_structured_reason_for_non_string(self) -> None:
        result = validate_signature_shape(None)
        self.assertFalse(result.valid)
        self.assertEqual(result.reason, "candidate must be a string")
        result2 = validate_signature_shape(b"A" * 86)
        self.assertFalse(result2.valid)
        self.assertEqual(result2.reason, "candidate must be a string")


# ---------------------------------------------------------------------------
# Parity with a real Ed25519 signature
# ---------------------------------------------------------------------------


class ParityWithRealEd25519Tests(unittest.TestCase):
    """A real Ed25519 signature must pass the surface check."""

    def test_real_signature_passes(self) -> None:
        priv = Ed25519PrivateKey.generate()
        # The data being signed does not matter; only the surface
        # of the resulting signature is being checked.
        sig_bytes = priv.sign(b"hello")
        self.assertEqual(len(sig_bytes), 64)
        encoded = base64.urlsafe_b64encode(sig_bytes).rstrip(b"=").decode("ascii")
        # Sanity: the canonical encoding is exactly 86 chars and
        # ends in one of the four reachable chars.
        self.assertEqual(len(encoded), 86)
        self.assertIn(encoded[-1], TAIL_CHARS)
        # The surface check must agree.
        self.assertTrue(is_canonical_signature_shape(encoded))
        result = validate_signature_shape(encoded)
        self.assertTrue(result.valid, msg=result.reason)

    def test_real_signatures_always_end_in_aqgw(self) -> None:
        # Generate 50 random signatures and confirm the tail is
        # always one of AQgw. This is a property of the encoding
        # of 64 raw bytes, not of the key or the data.
        for _ in range(50):
            priv = Ed25519PrivateKey.generate()
            sig_bytes = priv.sign(b"x")
            encoded = base64.urlsafe_b64encode(sig_bytes).rstrip(b"=").decode("ascii")
            self.assertEqual(len(encoded), 86)
            self.assertIn(encoded[-1], TAIL_CHARS)


# ---------------------------------------------------------------------------
# No amplification
# ---------------------------------------------------------------------------


class NoAmplificationTests(unittest.TestCase):
    """The error surface must not echo the input value."""

    def test_reason_never_includes_input_for_oversize_string(self) -> None:
        secret = "A" * 86 + "S"  # would-be "secret" payload
        result = validate_signature_shape(secret)
        self.assertFalse(result.valid)
        # The reason must not include the long run of A's (which
        # would otherwise be a covert side channel).
        self.assertNotIn("A" * 50, result.reason or "")

    def test_reason_never_includes_input_for_non_string(self) -> None:
        # Passing a long-ish bytes blob must not echo anything.
        blob = b"\x00" * 4096
        result = validate_signature_shape(blob)
        self.assertFalse(result.valid)
        self.assertEqual(result.reason, "candidate must be a string")

    def test_sig_shape_error_is_constructible(self) -> None:
        # The exception class is exposed for callers that want to
        # raise their own static-message errors. The constructor
        # takes a string and the test confirms it round-trips.
        err = SigShapeError("test message")
        self.assertEqual(str(err), "test message")


