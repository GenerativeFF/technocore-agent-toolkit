"""Unit tests for :mod:`src.technocore_sig_shape`.

The surface invariants are exhaustively enumerated. The test suite
covers the four reachable tail characters, the three rejected tail
positions, the full base64url alphabet (positive and negative), the
length boundary (85, 86, 87), the input-type matrix, the parity
with a real Ed25519 signature generated by the project's own
verifier module, and the no-amplification contract for the
``SigShapeError``/``SigShapeResult.reason`` surface.
"""
