# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------


class ConstantsTests(unittest.TestCase):
    """The exported constants must agree with the documented invariant."""

    def test_expected_length_is_86(self) -> None:
        # 64 bytes * 8 bits / 6 bits per base64url char = 85.33...,
        # rounded up to 86. This is the canonical unpadded length
        # for a 64-byte Ed25519 signature.
        self.assertEqual(EXPECTED_LENGTH, 86)

    def test_tail_chars_are_exactly_four(self) -> None:
        # 4 reachable values for the trailing 6-bit group of a
        # 64-byte signature.
        self.assertEqual(len(TAIL_CHARS), 4)
        self.assertEqual(len(TAIL_CHARS_STR), 4)

    def test_tail_chars_are_a_q_g_w(self) -> None:
        self.assertEqual(TAIL_CHARS, ("A", "Q", "g", "w"))
        self.assertEqual(TAIL_CHARS_STR, "AQgw")

    def test_allowed_chars_omits_padding(self) -> None:
        # base64url alphabet = standard base64 with '+' -> '-' and
        # '/' -> '_'. Padding '=' is forbidden in the canonical form.
        base64url_alphabet = (
            string.ascii_uppercase
            + string.ascii_lowercase
            + string.digits
            + "-_"
        )
        self.assertEqual(set(ALLOWED_CHARS), set(base64url_alphabet))
        self.assertNotIn("=", ALLOWED_CHARS)
        self.assertNotIn("+", ALLOWED_CHARS)
        self.assertNotIn("/", ALLOWED_CHARS)

    def test_version_is_a_positive_int(self) -> None:
        self.assertIsInstance(SIG_SHAPE_VERSION, int)
        self.assertGreaterEqual(SIG_SHAPE_VERSION, 1)


# ---------------------------------------------------------------------------
# is_canonical_signature_shape: happy path
# ---------------------------------------------------------------------------


def _make_valid_86_char_string(last_char: str) -> str:
    """Return an 86-char base64url string ending in ``last_char``.

    The 85 leading characters are all the most-common base64url
    char (``A``); the last char is the one under test.
    """
    assert last_char in TAIL_CHARS
    return ("A" * 85) + last_char


class HappyPathTests(unittest.TestCase):
    """A canonical 86-char base64url string ending in AQgw is valid."""

    def test_all_four_tail_chars_pass(self) -> None:
        for tail in TAIL_CHARS:
            s = _make_valid_86_char_string(tail)
            self.assertTrue(
                is_canonical_signature_shape(s),
                f"expected {s[-10:]!r} to be canonical",
            )

    def test_each_tail_char_has_a_positive_result(self) -> None:
        for tail in TAIL_CHARS:
            s = _make_valid_86_char_string(tail)
            result = validate_signature_shape(s)
            self.assertTrue(result.valid, msg=f"tail={tail!r}")
            self.assertIsNone(result.reason)

    def test_full_alphabet_string_is_valid(self) -> None:
        # A 64-byte string that, when base64url-encoded without
        # padding, lands at length 86 with a reachable tail.
        raw = bytes(range(64))  # 0..63
        encoded = base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")
        self.assertEqual(len(encoded), 86)
        self.assertIn(encoded[-1], TAIL_CHARS)
        self.assertTrue(is_canonical_signature_shape(encoded))


# ---------------------------------------------------------------------------
# is_canonical_signature_shape: length
# ---------------------------------------------------------------------------


class LengthTests(unittest.TestCase):
    """The length must be exactly 86."""

    def test_85_chars_is_rejected(self) -> None:
        s = "A" * 85
        self.assertEqual(len(s), 85)
        self.assertFalse(is_canonical_signature_shape(s))
        result = validate_signature_shape(s)
        self.assertFalse(result.valid)
        self.assertIn("length is 85", result.reason or "")

    def test_87_chars_is_rejected(self) -> None:
        # An 87-char string would correspond to a 65-byte tail, not
        # a 64-byte signature. The tail pattern can still match one
        # of AQgw for *some* inputs, so the length check is the
        # decisive rejection.
        s = "A" * 86 + "A"
        self.assertEqual(len(s), 87)
        self.assertFalse(is_canonical_signature_shape(s))
        result = validate_signature_shape(s)
        self.assertFalse(result.valid)
        self.assertIn("length is 87", result.reason or "")

    def test_empty_string_is_rejected(self) -> None:
        self.assertFalse(is_canonical_signature_shape(""))
        result = validate_signature_shape("")
        self.assertFalse(result.valid)
        self.assertIn("length is 0", result.reason or "")

    def test_very_long_string_is_rejected(self) -> None:
        s = "A" * 10_000
        self.assertFalse(is_canonical_signature_shape(s))


# ---------------------------------------------------------------------------
# is_canonical_signature_shape: tail character
# ---------------------------------------------------------------------------


class TailCharTests(unittest.TestCase):
    """Only the four reachable tail characters are valid."""

    def test_each_non_tail_uppercase_letter_is_rejected(self) -> None:
        # Test every uppercase letter that is NOT in TAIL_CHARS, to
        # lock down that the tail check is exhaustive and not just
        # a coincidence.
        for ch in "BCDEFGHIJKLMNOPRSTUVWXYZ":
            s = _make_valid_86_char_string("A")
            s = s[:-1] + ch
            self.assertFalse(
                is_canonical_signature_shape(s),
                f"expected tail {ch!r} to be rejected",
            )
            result = validate_signature_shape(s)
            self.assertFalse(result.valid)
            self.assertIn("last character", result.reason or "")

    def test_each_non_tail_lowercase_letter_is_rejected(self) -> None:
        # Exclude 'g' and 'w' (the two lowercase tail chars).
        for ch in "abcdefhijklmnopqrstuvwxyz".replace("g", "").replace("w", ""):
            s = _make_valid_86_char_string("A")
            s = s[:-1] + ch
            self.assertFalse(is_canonical_signature_shape(s))

    def test_each_digit_tail_is_rejected(self) -> None:
        for ch in "0123456789":
            s = _make_valid_86_char_string("A")
            s = s[:-1] + ch
            self.assertFalse(is_canonical_signature_shape(s))

    def test_dash_and_underscore_tails_are_rejected(self) -> None:
        # base64url maps '+' -> '-' and '/' -> '_'. The reachable
        # 6-bit values for the final group of a 64-byte tail are
        # 0, 16, 32, 48; their corresponding characters are exactly
        # the four in TAIL_CHARS. '-' is 0x2D = 45 = 0b101101, so
        # its low 4 bits are 0b1101 which is non-zero; '_' is 0x5F
        # = 0b1011111, also non-zero low 4 bits. Both are rejected.
        for ch in "-_":
            s = _make_valid_86_char_string("A")
            s = s[:-1] + ch
            self.assertFalse(is_canonical_signature_shape(s))

    def test_padding_equals_tail_is_rejected(self) -> None:
        # Padding '=' is forbidden by the canonical form. The
        # length check rejects an 87-char string with a trailing
        # '=' before the tail check is even reached.
        s = "A" * 85 + "="
        self.assertEqual(len(s), 86)
        # '=' is not in ALLOWED_CHARS, so the alphabet check rejects
        # it before the tail check fires.
        self.assertFalse(is_canonical_signature_shape(s))


# ---------------------------------------------------------------------------
# is_canonical_signature_shape: alphabet
# ---------------------------------------------------------------------------


class AlphabetTests(unittest.TestCase):
    """Every character must be in the unpadded base64url alphabet."""

    def test_standard_base64_plus_is_rejected(self) -> None:
        s = "A" * 85 + "+"  # '+' is standard base64, not base64url
        self.assertFalse(is_canonical_signature_shape(s))

    def test_standard_base64_slash_is_rejected(self) -> None:
        s = "A" * 85 + "/"
        self.assertFalse(is_canonical_signature_shape(s))

    def test_padding_equals_in_middle_is_rejected(self) -> None:
        s = "A" * 10 + "=" + "A" * 75
        self.assertEqual(len(s), 86)
        self.assertFalse(is_canonical_signature_shape(s))

    def test_whitespace_is_rejected(self) -> None:
        for ch in " \t\n\r":
            s = "A" * 85 + ch
            self.assertEqual(len(s), 86)
            self.assertFalse(is_canonical_signature_shape(s))

    def test_punctuation_is_rejected(self) -> None:
        for ch in "!@#$%^&*()[]{}<>?,.:;\"'\\|`~":
            s = "A" * 85 + ch
            self.assertEqual(len(s), 86)
            self.assertFalse(is_canonical_signature_shape(s))

    def test_unicode_is_rejected(self) -> None:
        # 86 codepoints of U+00E9 (é), each 1 Python char, but the
        # alphabet check rejects non-ASCII.
        s = "é" * 86
        self.assertEqual(len(s), 86)
        self.assertFalse(is_canonical_signature_shape(s))

    def test_alphabet_does_not_contain_plus_slash_equals(self) -> None:
        # Defensive: if anyone edits ALLOWED_CHARS by accident, we
        # catch it here.
        self.assertNotIn("+", ALLOWED_CHARS)
        self.assertNotIn("/", ALLOWED_CHARS)
        self.assertNotIn("=", ALLOWED_CHARS)


